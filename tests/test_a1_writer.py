def test_writer_audit_history_passthrough(monkeypatch):
    """新链路工具调用历史必须回流 state（银行审计），agent 标记为 report_writer"""
    import agents.report_writer as rw
    from utils.config import get_settings

    monkeypatch.setattr(get_settings(), "USE_MULTILEVEL_COMPRESSION", True)
    monkeypatch.setattr(rw, "is_llm_ready", lambda: True)

    st = _state_for_writer()
    st["tool_call_history"] = [{"agent": "financial_analyst", "tool": "query_fact", "ts": "x"}]

    def fake_with_tools(system_prompt, user_message, tools, max_rounds=None, on_tool_call=None):
        if on_tool_call:
            on_tool_call("query_fact", {"metric": "营业收入"}, "命中 204.42")
        return {"error": False, "content": "OK", "tool_calls": [{"tool": "query_fact"}], "rounds": 1}

    monkeypatch.setattr(rw, "safe_invoke_with_tools", fake_with_tools)

    out = rw.report_writer_node(st)
    calls = out.get("tool_call_history", [])
    assert len(calls) == 2, "Analyst 旧留痕 + Writer 本次调用都必须保留"
    last = calls[-1]
    assert last["agent"] == "report_writer"
    assert last["tool"] == "query_fact"
    assert "ts" in last and "result_len" in last, "审计字段必须齐全（谁/何时/工具/参数/返回体量）"


def test_writer_revision_mode_with_tools(monkeypatch):
    """修订模式: 反馈与上一版进 prompt，且仍挂工具（核对反馈涉及的数字）"""
    import agents.report_writer as rw
    from utils.config import get_settings

    monkeypatch.setattr(get_settings(), "USE_MULTILEVEL_COMPRESSION", True)
    monkeypatch.setattr(rw, "is_llm_ready", lambda: True)

    captured = {}

    def fake_with_tools(system_prompt, user_message, tools, **kw):
        captured["prompt"] = system_prompt
        captured["n_tools"] = len(tools)
        return {"error": False, "content": "# 修订版报告", "tool_calls": [], "rounds": 1}

    monkeypatch.setattr(rw, "safe_invoke_with_tools", fake_with_tools)

    st = _state_for_writer()
    st["review_feedback"] = "报告写营收 204.43 亿元与事实表 204.42 不符，请修正 [P 0]"
    st["prev_final_report"] = "# 旧报告\n营收 204.43 亿元 [P 0]"
    out = rw.report_writer_node(st)

    assert "修订" in captured["prompt"]
    assert "204.43 亿元与事实表" in captured["prompt"], "审查反馈必须进 prompt"
    assert "旧报告" in captured["prompt"], "上一版报告必须进 prompt"
    assert captured["n_tools"] == 3, "修订模式同样挂 3 工具供核对"
    assert "修订版报告" in out["final_report"]


def test_writer_fallback_on_llm_error_new_path(monkeypatch):
    """新链路 LLM 失败: 降级报告 + 工具留痕不丢（不再二次调旧路径浪费调用）"""
    import agents.report_writer as rw
    from utils.config import get_settings

    monkeypatch.setattr(get_settings(), "USE_MULTILEVEL_COMPRESSION", True)
    monkeypatch.setattr(rw, "is_llm_ready", lambda: True)

    def fake_with_tools(*a, **kw):
        return {"error": True, "message": "API 超时"}

    old_called = {}

    def fake_safe_invoke(*a, **kw):
        old_called["called"] = True
        return {"error": False, "content": "x"}

    monkeypatch.setattr(rw, "safe_invoke_with_tools", fake_with_tools)
    monkeypatch.setattr(rw, "safe_invoke", fake_safe_invoke)

    out = rw.report_writer_node(_state_for_writer())

    assert "简要版" in out["final_report"] or "免责" in out["final_report"], "必须产出降级报告"
    assert "old_called" not in old_called, "新链路失败不得回退再打一次旧路径 LLM"
    assert out["agent_status"]["report_writer"] == "done"
