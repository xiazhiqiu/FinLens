def test_writer_strips_llm_preamble(monkeypatch):
    """[A5] 工具循环最终回复的元评论前缀必须被剥离，报告从首个 H1 开始"""
    import agents.report_writer as rw
    from utils.config import get_settings

    monkeypatch.setattr(get_settings(), "USE_MULTILEVEL_COMPRESSION", True)
    monkeypatch.setattr(rw, "is_llm_ready", lambda: True)
    # 带英文元评论前缀 + 中间无干扰 H1 的回复
    noisy = 'I now have comprehensive data. Let me compile.\n\n---\n\n# 复星医药投资分析报告\n\n## 一、核心结论\n稳健 [P 0]'
    monkeypatch.setattr(rw, "safe_invoke_with_tools",
                        lambda *a, **kw: {"error": False, "content": noisy, "tool_calls": [], "rounds": 1})

    out = rw.report_writer_node(_state_for_writer())

    assert out["final_report"].lstrip().startswith("# "), "报告必须从 H1 开始"
    assert "I now have" not in out["final_report"], "元评论不得泄漏进报告"
    assert "复星医药投资分析报告" in out["final_report"]
    # 无 H1 的回复（纯文本）：原样保留，不误删
    monkeypatch.setattr(rw, "safe_invoke_with_tools",
                        lambda *a, **kw: {"error": False, "content": "OK 纯文本报告内容", "tool_calls": [], "rounds": 1})
    out2 = rw.report_writer_node(_state_for_writer())
    assert "纯文本报告内容" in out2["final_report"]


def test_writer_uses_multilevel_path_when_flag_on(monkeypatch):
    import agents.report_writer as rw
    from utils.config import get_settings

    monkeypatch.setattr(get_settings(), "USE_MULTILEVEL_COMPRESSION", True)
    monkeypatch.setattr(rw, "is_llm_ready", lambda: True)

    captured = {}

    def fake_with_tools(system_prompt, user_message, tools, **kw):
        captured["n_tools"] = len(tools)
        captured["tool_names"] = sorted(t.name for t in tools)
        captured["prompt"] = system_prompt
        return {"error": False, "content": "# 复星医药投资分析报告\n营收 204.42 亿元 [P 0]", "tool_calls": [], "rounds": 1}

    monkeypatch.setattr(rw, "safe_invoke_with_tools", fake_with_tools)

    out = rw.report_writer_node(_state_for_writer())

    assert "204.42" in out["final_report"]
    assert captured["n_tools"] == 3, "必须挂载 3 个上下文工具"
    assert captured["tool_names"] == ["fetch_context", "query_fact", "search_section"]
    # 装配后的年报内容必须进 prompt（不再消费 pdf_summary）
    assert "PDF 年报内容" in captured["prompt"]
    assert "204.42" in captured["prompt"], "L1 表格数字必须经装配注入"
    # Analyst 结论是 Writer 的素材基础
    assert "营收 204.42 亿元，增长稳健" in captured["prompt"]
    # 统一后处理（免责声明 + 版本脚注）
    assert "免责" in out["final_report"] or "不构成" in out["final_report"]
    assert "Generated by FinScope" in out["final_report"]
    assert "tool_call_history" in out
    assert out["agent_status"]["report_writer"] == "done"


