def test_writer_keeps_old_path_when_flag_off(monkeypatch):
    import agents.report_writer as rw
    from utils.config import get_settings

    monkeypatch.setattr(get_settings(), "USE_MULTILEVEL_COMPRESSION", False)
    monkeypatch.setattr(rw, "is_llm_ready", lambda: True)
    called_new = {}

    def fake_with_tools(*a, **kw):
        called_new["called"] = True
        return {"error": False, "content": "x"}

    def fake_safe_invoke(system_prompt, user_message, **kw):
        called_new["old_prompt"] = system_prompt
        return {"error": False, "content": "# 旧路径报告\n营收稳健 [P 1]"}

    monkeypatch.setattr(rw, "safe_invoke_with_tools", fake_with_tools)
    monkeypatch.setattr(rw, "safe_invoke", fake_safe_invoke)

    out = rw.report_writer_node(_state_for_writer())

    assert "called" not in called_new, "flag 关闭不得走工具链路"
    assert "旧路径报告" in out["final_report"]
    assert "Generated by FinScope" in out["final_report"], "旧路径后处理行为不变"
    # [A4] 旧路径已无 PDF 内容可消费（pdf_sections/pdf_summary 字段删除），
    # 基础上下文仍含实体/市场数据/分析结论
    assert "深度分析结论" in called_new["old_prompt"]
    assert "PDF 全文摘要" not in called_new["old_prompt"]


